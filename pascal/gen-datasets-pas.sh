#!/bin/sh
#
# Generate src/ustratadatasets.pas from the datasets.tsv of geant4-installers.
#
#   ./gen-datasets-pas.sh <geant4-installers>/datasets.tsv > src/ustratadatasets.pas

set -eu

table=${1:?usage: gen-datasets-pas.sh <datasets.tsv>}

[ -r "$table" ] || { echo "gen-datasets-pas.sh: no $table" >&2; exit 1; }

version=$(sed -n 's/^# Geant4 \([0-9.]*\) datasets.*/\1/p' "$table" | head -1)
count=$(awk -F'\t' '!/^#/ && NF >= 5' "$table" | wc -l | tr -d ' ')

cat <<EOF
unit uStrataDatasets;

// The Geant4 $version datasets: what they are called, what they are worth and
// where to get them.
//
// GENERATED by pascal/gen-datasets-pas.sh from the datasets.tsv of
// geant4-installers.  Do not edit; regenerate it.

{\$mode objfpc}{\$H+}

interface

type
  TStrataDataset = record
    Directory: String;     // what it unpacks to, e.g. G4EMLOW8.8
    Variable: String;      // the environment variable Geant4 looks it up with
    Archive: String;       // the file to fetch
    MD5: String;           // Geant4's own checksum for it
    Required: Boolean;     // Geant4 aborts the run without it
    Description: String;
  end;

const
  // Where Geant4 publishes them. The redirect to geant4-data.web.cern.ch is
  // followed by whatever does the transfer
  kStrataDatasetBaseURL = 'https://cern.ch/geant4-data/datasets';

  kStrataDatasetCount = $count;

  kStrataDatasets: array[0..kStrataDatasetCount - 1] of TStrataDataset = (
EOF

awk -F'\t' '
    /^#/ || NF < 5 { next }
    {
        dir = $1; var = $2; archive = $3; md5 = $4; required = $5
        desc = $6
        gsub(/\047/, "\047\047", desc)
        n++
        rows[n] = sprintf("    (Directory: \047%s\047; Variable: \047%s\047;\n     Archive: \047%s\047;\n     MD5: \047%s\047;\n     Required: %s;\n     Description: \047%s\047)",
                          dir, var, archive, md5,
                          (required == 1) ? "True " : "False", desc)
    }
    END {
        for (i = 1; i <= n; i++)
            printf "%s%s\n", rows[i], (i < n) ? "," : ""
    }
' "$table"

cat <<'EOF'
  );

implementation

end.
EOF
